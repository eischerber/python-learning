# 顺手验证 W2D6 任务 3 的技巧：负号 + 元组实现"双条件排序"
students = [("葵", 74), ("小明", 92), ("小红", 88), ("阿强", 92)]
double_sort = sorted(students, key=lambda s: (-s[1], s[0]))
print(double_sort)
# 期望: [('小明', 92), ('阿强', 92), ('小红', 88), ('葵', 74)]
# 分数降序（-分数越大=分数越小排后面），同分按名字升序。
