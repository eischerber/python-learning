# W2D2（函数·中）：默认参数 / 关键字参数 / 作用域
# ============================================================
# 原理（先懂再写）：
# 1. 默认参数：def greet(name, greeting="你好")
#    → 调用时不传 greeting 就自动用"你好"，传了就用你传的。
#    用途：大部分时候一样、偶尔要改的参数，设成默认值省事。
# 2. 关键字参数：greet(name="葵", greeting="早上好")
#    → 按"名字="传参，顺序可以乱，可读性强。
# 3. 作用域（重点，最容易出静默 bug 的地方）：
#    - 函数里建的变量是【局部】，函数外看不见，出了函数就没了
#    - 函数外的变量是【全局】，函数里能"读"，但不能随便"改"
#    - 函数里给一个名字赋值 = 新建了一个局部变量（同名遮蔽全局！）
#      这和 W1D1 你踩过的"sum/max 遮蔽内置函数"是同一个机制：
#      都叫"局部名字盖住外面的名字"
# 规矩：下面 3 段先【手写预测】输出，再运行验证，全对才算过。
# ============================================================

# ---- 第 1 段：默认参数 ----
# 预测：这三次调用分别打印什么？
def greet(name, greeting="你好"):
    print(greeting + ", " + name)

# TODO 3：写三次调用：①只传 name ②两个位置参数 ③greeting 用关键字参数传
