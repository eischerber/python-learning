# ---- 主任务：把"求最大值"封装成 find_max(lst) ----
# 要求：空手起手逻辑（不许用内置 max），用 best 起手逐个比
# TODO 1：写 def find_max(lst): ... return ...
scores = [90, 55, 78, 88, 62, 95, 71, 83, 59, 100, 66]

def find_max(lst):
    best = lst[0]
    for s in lst:
        if s>best:
         best = s
    return  best

print(find_max(scores))        # 100
print(find_max([-5, -2, -9]))  # -2（全负数也要对）
print(find_max([3, 3, 3]))     # 3
 

    


