# 【项目1是什么】媒体文件整理器：给一个乱糟糟的文件夹，按扩展名把文件
#   自动分到 图片/文档/视频/其他 子文件夹。这是你的第一个 Python 项目，
#   做完能进作品集。
# 【今天这步的原理】os.listdir(路径) 返回【文件名字符串列表】，只列这一层，
#   【不递归】进子文件夹。它是"看见文件"的第一步。
#   关键坑：它只给文件名（"a.jpg"），不是完整路径。以后要移动/打开它，
#   必须用 os.path.join(文件夹, 文件名) 拼出完整路径——今天先把这个习惯立下。
# 【W2 融进 W3】这里开始你就地学函数：主程序尽量塞进 main()，
#   末尾加 if __name__ == "__main__": main()（防止被 import 时误执行）。
# ============================================================

import os

# TODO 1：把 folder 改成一个真实存在的测试文件夹路径（建议专门建一个"测试文件夹"，
#   里面随便放几个假文件，别拿 code/ 真目录练手——W3D2 要移动文件，误移就麻烦）
folder = r"E:\01-课程作业\AE"

# TODO 2：写 main()——用 os.listdir 列出 folder 下所有文件名，逐个打印
#   提示：files = os.listdir(folder) → for f in files: print(f)
#   进阶：把每个文件名用 os.path.join(folder, f) 拼成完整路径一起打印，
#         对比"文件名"和"完整路径"的区别（这是 W3D2 分类移动的基础）。
def main():
    files = os.listdir(folder)
    for f in files:
       print(f)
       print(os.path.join(folder,f))
   


if __name__ == "__main__":
    main()

# 【验收】对着真实文件夹跑出全部文件名列表；能说出 os.listdir 给的是文件名还是路径。
